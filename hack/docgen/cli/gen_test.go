func TestEscapeProse(t *testing.T) {
	cases := map[string]string{
		"a config-template-<name> ConfigMap":   "a config-template-&lt;name&gt; ConfigMap",
		"run `vela up <file>` to deploy":       "run `vela up <file>` to deploy",
		"`<a>` and <b> and `<c>`":              "`<a>` and &lt;b&gt; and `<c>`",
		"* [vela mcp](vela_mcp.md)\t - Serve.": "* [vela mcp](vela_mcp.md)\t - Serve.",
		"":                                     "",
	}
	for in, want := range cases {
		if got := escapeProse(in); got != want {
			t.Errorf("escapeProse(%q) = %q, want %q", in, got, want)
		}
	}
}

func TestPruneStalePages(t *testing.T) {
	root := &cobra.Command{Use: "vela"}
	crate := &cobra.Command{Use: "crate", Run: func(*cobra.Command, []string) {}}
	crate.AddCommand(&cobra.Command{Use: "deploy", Run: func(*cobra.Command, []string) {}})
	root.AddCommand(crate)
	root.AddCommand(&cobra.Command{Use: "old", Hidden: true, Run: func(*cobra.Command, []string) {}})

	dir := t.TempDir()
	generated := "---\ntitle: x\n---\n\n#### Go Back to [CLI Commands](vela.md) Homepage.\n\n\n" + pageFooter + "\n"
	files := map[string]string{
		"vela.md":              generated,
		"vela_crate.md":        generated,
		"vela_crate_deploy.md": generated,
		// Pages of commands that were renamed away or hidden.
		"vela_module.md":        generated,
		"vela_module_deploy.md": generated,
		"vela_old.md":           generated,
		// A page from a run that stopped before the footer was rewritten.
		"vela_raw.md": "## vela raw\n\n###### Auto generated by spf13/cobra on 26-Nov-2026\n",
		// Hand-written pages, one that mentions the footer text in prose, and
		// files that are not CLI pages.
		"vela_notes.md":  "---\ntitle: notes\n---\n\nWritten by hand.\n",
		"vela_about.md":  "---\ntitle: about\n---\n\nThese pages are Auto generated by a script in KubeVela.\n",
		"velaux.md":      generated,
		"vela_crate.txt": generated,
		"README.md":      generated,
	}
	for name, content := range files {
		if err := os.WriteFile(filepath.Join(dir, name), []byte(content), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	if err := os.Mkdir(filepath.Join(dir, "vela_dir.md"), 0o750); err != nil {
		t.Fatal(err)
	}

	removed, err := PruneStalePages(root, dir)
	if err != nil {
		t.Fatal(err)
	}
	sort.Strings(removed)
	wantRemoved := []string{"vela_module.md", "vela_module_deploy.md", "vela_old.md", "vela_raw.md"}
	if !reflect.DeepEqual(removed, wantRemoved) {
		t.Errorf("removed %v, want %v", removed, wantRemoved)
	}

	entries, err := os.ReadDir(dir)
	if err != nil {
		t.Fatal(err)
	}
	var left []string
	for _, e := range entries {
		left = append(left, e.Name())
	}
	wantLeft := []string{"README.md", "vela.md", "vela_about.md", "vela_crate.md", "vela_crate.txt", "vela_crate_deploy.md", "vela_dir.md", "vela_notes.md", "velaux.md"}
	if !reflect.DeepEqual(left, wantLeft) {
		t.Errorf("left %v, want %v", left, wantLeft)
	}
}
