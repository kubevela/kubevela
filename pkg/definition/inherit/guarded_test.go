// guardedBase writes some fields only under a condition: one inside a list
// item, one in a plain struct, and keys generated by a `for`.
const guardedBase = `
output: {
	apiVersion: "apps/v1"
	kind:       "Deployment"
	spec: template: spec: containers: [{
		name: "web"
		if parameter.cpu != _|_ {
			resources: limits: cpu: parameter.cpu
		}
	}]
}
outputs: cfg: {
	apiVersion: "v1"
	kind:       "ConfigMap"
	data: {
		if parameter.mode != _|_ {
			mode: parameter.mode
		}
		for k, v in parameter.extra {
			"x-\(k)": v
		}
	}
}
parameter: {
	cpu?:  string
	mode?: string
	extra: [string]: string
}
`

const guardedCPUMessage = "component child sets output.spec.template.spec.containers[0].resources.limits.cpu, " +
	"which base sets only when `if parameter.cpu != _|_`; an Application that meets that condition would be refused. " +
	"Pass a value to base through `$super: properties` instead"

var _ = Describe("a field the parent writes only under a condition", func() {
	base := Level{Name: "base", Template: guardedBase}
	child := func(tpl string) Level { return Level{Name: "child", Template: silentMiddle + tpl} }
	admit := func(tpl string, ancestors ...Level) error {
		own := cuecontext.New().CompileString(tpl + "\n$super: _\nparameter: _\ncontext: _\n")
		Expect(own.Err()).NotTo(HaveOccurred())
		return CheckOverrides(context.Background(), "child", child(tpl), own, ancestors, ComponentSurface, admissionCompile())
	}

	It("is refused when the child is written, naming the condition", func() {
		Expect(admit("output: spec: template: spec: containers: [{resources: limits: cpu: \"250m\"}]\n", base)).
			To(MatchError(guardedCPUMessage))
	})

	It("is refused at render, even for an Application that does not meet the condition", func() {
		_, err := renderComponent(child("output: spec: template: spec: containers: [{resources: limits: cpu: \"250m\"}]\n"), base)
		Expect(err).To(MatchError(guardedCPUMessage))
	})

	DescribeTable("is refused at admission and at render",
		func(tpl, want string) {
			Expect(admit(tpl, base)).To(MatchError(ContainSubstring(want)))
			_, err := renderComponent(child(tpl), base)
			Expect(err).To(MatchError(ContainSubstring(want)))
		},
		Entry("a field in a plain struct", "outputs: cfg: data: mode: \"fast\"\n",
			"component child sets outputs.cfg.data.mode, which base sets only when `if parameter.mode != _|_`"),
		Entry("a key a `for` generates, matched by its pattern", "outputs: cfg: data: \"x-team\": \"a\"\n",
			"component child sets outputs.cfg.data.x-team, which base sets only when `for k, v in parameter.extra`"),
		Entry("a field below a guarded leaf",
			"output: spec: template: spec: containers: [{resources: limits: cpu: \"250m\"}]\n",
			"component child sets output.spec.template.spec.containers[0].resources.limits.cpu, which base sets only when"),
	)

	DescribeTable("accepts",
		func(tpl string) {
			Expect(admit(tpl, base)).To(Succeed())
			_, err := renderComponent(child(tpl), base)
			Expect(err).NotTo(HaveOccurred())
		},
		Entry("a sibling of the guarded field",
			"output: spec: template: spec: containers: [{resources: limits: memory: \"128Mi\"}]\n"),
		Entry("a key the `for` pattern does not match", "outputs: cfg: data: other: \"a\"\n"),
		Entry("its own entry for the output that holds the guarded field, after leaving the parent's out",
			"$inherit: {outputs: {cfg: false}}\noutputs: cfg: {apiVersion: \"v1\", kind: \"ConfigMap\", data: mode: \"fast\"}\n"),
		Entry("a value passed the right way", "$super: properties: cpu: \"250m\"\n"),
	)

	It("does not compare an output a middle level left out", func() {
		middle := Level{Name: "middle", Template: silentMiddle +
			"$inherit: {outputs: {cfg: false}}\noutputs: cfg: {apiVersion: \"v1\", kind: \"ConfigMap\"}\n"}
		leaf := Level{Name: "leaf", Template: silentMiddle + "outputs: cfg: data: mode: \"fast\"\n"}
		_, err := renderComponent(leaf, middle, base)
		Expect(err).NotTo(HaveOccurred())
	})

	It("accepts a field added beside a guarded embedding, which declares no field", func() {
		embedding := Level{Name: "base", Template: "output: {\n\tkind: \"Deployment\"\n\tmetadata: labels: {\n" +
			"\t\tif parameter.labels != _|_ {\n\t\t\tparameter.labels\n\t\t}\n\t}\n}\nparameter: labels?: [string]: string\n"}
		tpl := "output: metadata: labels: team: \"a\"\n"
		Expect(admit(tpl, embedding)).To(Succeed())
		_, err := renderComponent(child(tpl), embedding)
		Expect(err).NotTo(HaveOccurred())
	})

	Context("when the guarded value can be a struct", func() {
		annotated := Level{Name: "base", Template: `
output: {
	apiVersion: "apps/v1"
	kind:       "Deployment"
	spec: template: metadata: {
		if parameter.annotations != _|_ {
			annotations: parameter.annotations
		}
	}
}
parameter: annotations?: [string]: string
`}
		tpl := "$super: properties: annotations: parameter.annotations\n" +
			"output: spec: template: metadata: annotations: team: \"payments\"\n" +
			"parameter: annotations?: [string]: string\n"
		renderWith := func(params string) (*Result, error) {
			return Render(context.Background(), []Level{{Name: "child", Template: tpl}, annotated},
				params, contextFile, ComponentSurface, SameCompiler(testCompile()))
		}

		It("accepts a key added below it when the child is written", func() {
			Expect(admit(tpl, annotated)).To(Succeed())
		})

		It("renders both keys for an Application that passes another one", func() {
			res, err := renderWith(`parameter: annotations: owner: "bob"`)
			Expect(err).NotTo(HaveOccurred())
			got := map[string]string{}
			Expect(lookup(res.Value, "output.spec.template.metadata.annotations").Decode(&got)).To(Succeed())
			Expect(got).To(Equal(map[string]string{"owner": "bob", "team": "payments"}))
		})

		It("leaves a key both set to the existing override check", func() {
			_, err := renderWith(`parameter: annotations: team: "other"`)
			Expect(err).To(MatchError(ContainSubstring(
				"component child sets output.spec.template.metadata.annotations.team, which base already sets; " +
					"pass a value to base through `$super: properties` instead")))
			Expect(err.Error()).NotTo(ContainSubstring("sets only when"))
		})
	})

	It("is refused below a guarded list parameter", func() {
		listed := Level{Name: "base", Template: "output: {\n\tkind: \"Deployment\"\n\tspec: {\n" +
			"\t\tif parameter.args != _|_ {\n\t\t\targs: parameter.args\n\t\t}\n\t}\n}\nparameter: args?: [...string]\n"}
		tpl := "output: spec: args: [\"--verbose\"]\n"
		want := "component child sets output.spec.args[0], which base sets only when `if parameter.args != _|_`"
		Expect(admit(tpl, listed)).To(MatchError(ContainSubstring(want)))
		_, err := renderComponent(child(tpl), listed)
		Expect(err).To(MatchError(ContainSubstring(want)))
	})

	It("accepts a pod label and a pod annotation added to the shipped webservice", func() {
		b, err := os.ReadFile("testdata/webservice.cue")
		Expect(err).NotTo(HaveOccurred())
		webservice := Level{Name: "webservice", Template: string(b)}
		tpl := "$super: properties: {\n\timage: parameter.image\n" +
			"\tif parameter.annotations != _|_ {annotations: parameter.annotations}\n}\n" +
			"output: spec: template: metadata: {\n\tlabels: team: \"payments\"\n\tannotations: team: \"payments\"\n}\n" +
			"parameter: {\n\timage: string\n\tannotations?: [string]: string\n}\n"
		Expect(admit(tpl, webservice)).To(Succeed())
		res, err := Render(context.Background(), []Level{{Name: "child", Template: tpl}, webservice},
			`parameter: {image: "nginx", annotations: owner: "bob"}`, webserviceContext, ComponentSurface, SameCompiler(testCompile()))
		Expect(err).NotTo(HaveOccurred())
		label, err := lookup(res.Value, `output.spec.template.metadata.labels.team`).String()
		Expect(err).NotTo(HaveOccurred())
		Expect(label).To(Equal("payments"))
		annotation, err := lookup(res.Value, `output.spec.template.metadata.annotations.team`).String()
		Expect(err).NotTo(HaveOccurred())
		Expect(annotation).To(Equal("payments"))
		owner, err := lookup(res.Value, `output.spec.template.metadata.annotations.owner`).String()
		Expect(err).NotTo(HaveOccurred())
		Expect(owner).To(Equal("bob"), "the Application's annotation reached the parent and merged with the child's")
	})

	It("keeps the existing message for a field the parent writes unconditionally", func() {
		_, err := renderComponent(child("output: spec: template: spec: containers: [{name: \"other\"}]\n"), base)
		Expect(err).To(MatchError(ContainSubstring(
			"component child sets output.spec.template.spec.containers[0].name, but base fixes it to \"web\" and a child cannot change it")))
	})

	It("is refused for a trait's patch", func() {
		traitBase := Level{Name: "base-trait", Template: "patch: spec: {\n\tif parameter.replicas != _|_ {\n\t\treplicas: parameter.replicas\n\t}\n}\nparameter: replicas?: int\n"}
		_, err := renderTrait(Level{Name: "child-trait", Template: silentMiddle + "patch: spec: replicas: 3\n"}, traitBase)
		Expect(err).To(MatchError(
			"trait child-trait sets patch.spec.replicas, which base-trait sets only when `if parameter.replicas != _|_`; " +
				"an Application that meets that condition would be refused. Pass a value to base-trait through `$super: properties` instead"))
	})

	Context("reading the guarded fields off a template", func() {
		paths := func(tpl string) []string {
			var out []string
			for _, g := range guardedFields(Level{Name: "base", Template: tpl}, ComponentSurface) {
				out = append(out, strings.Join(g.path, " ")+" | "+g.cond)
			}
			return out
		}

		It("reads nothing from a template with no comprehension", func() {
			Expect(guardedFields(Level{Name: "base", Template: overrideBase}, ComponentSurface)).To(BeEmpty())
		})

		It("joins nested clauses and ignores fields off the surface", func() {
			Expect(paths("output: {\n\tif parameter.a {\n\t\tif parameter.b {\n\t\t\tx: 1\n\t\t}\n\t}\n}\n" +
				"parameter: {\n\tif true {\n\t\ty: int\n\t}\n}\n")).
				To(ConsistOf("output x | if parameter.a if parameter.b"))
		})

		It("gives items after a list comprehension an index known only at render", func() {
			Expect(paths("output: args: [for a in parameter.args {a}, \"last\"]\n")).
				To(ConsistOf("output args [*] | for a in parameter.args"))
		})
	})

	It("keeps refusing below a guarded value that may be a scalar as well as a map", func() {
		either := Level{Name: "base", Template: "output: {\n\tkind: \"Deployment\"\n\tspec: template: metadata: {\n" +
			"\t\tif parameter.annotations != _|_ {\n\t\t\tannotations: parameter.annotations\n\t\t}\n\t}\n}\n" +
			"parameter: annotations?: string | {[string]: string}\n"}
		Expect(admit("output: spec: template: metadata: annotations: team: \"payments\"\n", either)).To(
			MatchError(ContainSubstring("which base sets only when `if parameter.annotations != _|_`")))
	})

	It("points at a separate definition when the condition is on context", func() {
		onContext := Level{Name: "base", Template: "output: {\n\tkind: \"Deployment\"\n\tspec: {\n" +
			"\t\tif context.namespace == \"prod\" {\n\t\t\treplicas: 3\n\t\t}\n\t}\n}\nparameter: {}\n"}
		Expect(admit("output: spec: replicas: 2\n", onContext)).To(MatchError(ContainSubstring(
			"which base sets only when `if context.namespace == \"prod\"`; an Application that meets that condition would be refused. " +
				"To use another value, write a definition that does not extend base")))
	})
})
